    }
}

/**
 * Release signing. Locally it reads `src-tauri/gen/android/keystore.properties`
 * (git-ignored — see scripts/android/create-keystore.sh); in CI the same values
 * come from MADSHOTS_* environment variables. With neither, release builds come
 * out unsigned and scripts/android/build-release.sh refuses to ship them.
 */
val keystoreProperties = Properties().apply {
    val propFile = rootProject.file("keystore.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}
fun signingValue(env: String, key: String): String? =
    System.getenv(env)?.takeIf { it.isNotBlank() } ?: keystoreProperties.getProperty(key)
val releaseStoreFile = signingValue("MADSHOTS_KEYSTORE_PATH", "storeFile")

